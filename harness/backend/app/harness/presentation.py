# --------------------------------------------------------------------- entry point

def compose(ctx_tool, concept_id: str, options: Mapping[str, Any] | None = None) -> dict[str, Any]:
    """Build the whole presentation from one concept.

    Returns the deck, the script, the timeline, the subtitle track and the rendered HTML, so
    every stage's output is separately inspectable rather than collapsed into one opaque
    artefact. The research's complaint about this format was precisely that its stages are
    invisible, and a pipeline whose intermediate states cannot be read cannot be corrected.
    """
    from . import generate

    options = dict(options or {})
    context = generate.retrieve(ctx_tool, concept_id)
    segments = build_segments(context,
                              include_visuals=bool(options.get('include_visuals', True)),
                              include_check=bool(options.get('include_check', True)))
    segments, mode, notes = _enhance(ctx_tool, segments, options)
    segments = timeline(segments)

    # Optional enrichments attach to the segment whose subject they match, so a photograph or
    # a simulation lands on the slide it illustrates rather than in a separate list.
    settings = getattr(ctx_tool, 'settings', None)
    enrichments: list[str] = []
    # Images are on unless the caller says otherwise. A deck of slides with no picture is a
    # wall of text; a deck with a *decorative* pattern where a figure belongs is worse than
    # that, because it reads as evidence. The shipped pack answers first and costs nothing —
    # a dict lookup and a file copy — so it is always consulted, including on the desktop
    # build where the network is off by policy. A live search is only made when the caller
    # explicitly asks for one, because that is a network fetch on a request path and a deck
    # must not stop working when the internet does.
    wants_image = options.get('include_image', True) is not False
    if wants_image and settings is not None:
        from . import media as media_pipeline
        found = None
        shipped = media_pipeline.shipped_for(settings, concept_id)
        if shipped is not None:
            found = {'asset': shipped, 'outcome': 'shipped'}
        elif options.get('include_image') is True:
            found = media_pipeline.find_image(settings, context.title,
                                              summary=context.summary)
        if found and found.get('asset'):
            asset = found['asset']
            target = next((s for s in segments if s.layout == 'idea'), segments[0])
            # ``type`` plus the shared payload: the native deck renders ``photograph``, and
            # ``deck.from_presentation`` reads ``sha256``/``attribution`` off the same dict to
            # place a real image element in an editable deck.
            target.visual = {'type': 'photograph', **media_pipeline.asset_payload(asset)}
            enrichments.append(f"photograph from {asset.get('source')} "
                               f"({asset.get('licence_code')})")
        else:
            enrichments.append('no curated photograph for this concept '
                               f"({(found or {}).get('outcome', 'not in the shipped pack')})")
    if options.get('include_simulation') and settings is not None:
        from .. import simulation_map
        course_id = str(options.get('course_id') or '')
        if course_id:
            sims = simulation_map.for_concept(settings, course_id, context.title)
            ready = [s for s in sims.get('simulations', []) if s.get('status') == 'ready']
            if ready:
                target = next((s for s in segments if s.layout == 'figure'), None) or segments[0]
                target.visual = {'type': 'simulation', **ready[0]}
                enrichments.append(f"simulation: {ready[0].get('title')}")

    notes = [*notes, *([f'Enrichment: {e}' for e in enrichments] if enrichments else [])]
    return {
        'kind': 'presentation',
        'concept_id': concept_id,
        'title': f'{context.title} — narrated deck',
        'mode': mode,
        'method': {
            'narrator': 'single',
            'assembly': 'audio-led: each slide\'s duration is its narration estimate plus a '
                        f'{SLIDE_PAD_SECONDS}s pad, accumulated into a timeline',
            'visuals': 'deterministic figures, licence-cleared photographs and provider '
                       'simulations only; no image model',
            'editable': 'the script and timeline are emitted as data alongside the render',
            'words_per_minute': WORDS_PER_MINUTE,
        },
        'slides': [s.to_dict() for s in segments],
        'script': [{'index': s.index, 'layout': s.layout, 'text': s.narration,
                    'start': round(s.start, 3), 'end': round(s.end, 3)} for s in segments],
        'total_seconds': round(sum(s.duration for s in segments), 3),
        'citations': list(context.citations),
        'vtt': vtt(segments),
        'html': render_html(f'{context.title} — narrated deck', segments,
                            meta={'mode': mode,
                                  'provenance_note': (
                                      'Narration and figures are derived from this project\'s own '
                                      'curriculum graph and authored lesson content. External '
                                      'references are links, never copied content.')},
                            course=options.get('course_label', '')),
        'notes': notes,
    }
