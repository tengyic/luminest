"""Writing lessons *into* a shipped course (the overlay path).

The claim under test is narrow and load-bearing: the harness can deepen a course it did
not author without duplicating it. Before this path existed, the foundry could only build
a *new* course, so a pack with 57 concepts and 0 lessons had exactly two futures - stay a
map with a glossary, or be replaced by a second course with different ids, which would
split a learner's progress between two graphs.

What must hold, and why each one is a test rather than a comment:

* **Structure comes from the pack, not from the model.** An overlay that could rename a
  concept or move it to another unit would silently invalidate every stored attempt,
  prerequisite edge and diagnosis that names that node.
* **The ``generated`` flag goes away, and with it the old items.** The flag is what
  ``authored_share`` counts, and the generated items ask "which statement best describes
  X" about a sentence the new lesson no longer contains.
* **Withdrawal is exact.** A course that comes back *almost* the way it was is worse than
  one that cannot be withdrawn, because the difference is invisible in every surface.
"""

from __future__ import annotations

import pytest

from app import courses, curriculum
from app.harness.authoring import audit as audit_module, blueprint, registry, synthesize

COURSE_ID = 'ap_microeconomics'
#: A concept with an honest diagram and one without, so the figure wiring is exercised in
#: both directions in one pass. ``price_elasticity_of_demand`` draws the elasticity
#: template; ``accounting_profit_versus_economic_profit`` is an accounting distinction with
#: no market to draw, which is exactly the case where a fabricated figure would teach the
#: wrong lesson.
GRAPH_CONCEPT = 'ap_microeconomics_price_elasticity_of_demand'
BARE_CONCEPT = 'ap_microeconomics_accounting_profit_versus_economic_profit'


@pytest.fixture(autouse=True)
def clean_foundry():
    registry.reset()
    yield
    registry.reset()


@pytest.fixture
def base_entries():
    return curriculum.course_concepts(COURSE_ID)


def _written_document(entries, concept_ids):
    """A framed blueprint with the depth fields filled in, as the model would return it.

    Prose only. That is not a shortcut: :func:`draft.expand` asks the model for seven
    prose fields per concept and nothing else, so a fixture that also hand-wrote items
    would be describing a pipeline that does not exist - and it would hide the fact that
    the item layer has to be regenerated by the overlay itself.
    """
    course_meta = {'id': COURSE_ID, 'title': 'AP Microeconomics', 'subject': 'Microeconomics',
                   'description': 'Markets, firms and market failure.', 'expected_weeks': 24,
                   'level': 'intro'}
    chosen = [entry for entry in entries if entry['id'] in concept_ids]
    document = blueprint.frame_from_entries(course_meta, chosen)
    for unit in document['units']:
        for concept in unit['concepts']:
            # Keyed on the title so two concepts never supply identical prose: identical
            # text would collapse the distractor pool, which is a property of this fixture
            # rather than of a course a model wrote.
            title = concept['title']
            concept.update({
                'summary': f'{title} is the relation this lesson is about, and the unit '
                           f'fixes the conditions under which it holds so that the '
                           f'direction of a change can be read off it.',
                'example': ['Pick a price and read the quantity demanded off the curve.',
                            'Lower the price and read the larger quantity that follows.',
                            'State the direction of the change in one sentence.'],
                'misconception': f'{title} is a statement about how much people want the '
                                 f'good rather than how much they will buy at a price.',
                'correction': f'{title} is about the relation, not about the label: the '
                              f'label is a name for the relation and changing it changes '
                              f'nothing.',
                'application': f'Given a case the lesson does not state, say which part '
                               f'of {title} fixes the answer and which part is free.',
                'definition': f'{title} is the relation this lesson names, stated in one '
                              f'sentence so that it can be recalled without the '
                              f'surrounding discussion.',
            })
    return document


def test_framing_preserves_the_courses_own_structure(base_entries):
    """The frame is a copy of the pack, not a new design."""
    document = blueprint.frame_from_entries(
        {'id': COURSE_ID, 'title': 'AP Microeconomics', 'subject': 'Microeconomics',
         'description': 'x', 'expected_weeks': 24}, list(base_entries.values()))
    plan, problems = blueprint.parse(document, author='template')

    assert plan is not None
    assert not blueprint.blocking(problems)
    framed = {concept.id for concept in plan.concepts()}
    assert framed == set(base_entries), 'every pack concept must be framed, and no other'
    assert len(plan.units) == 9, 'the pack declares nine units'
    assert plan.profile.shape.concepts_per_unit_max >= 9, (
        'the widest unit is nine concepts, so the ceiling is raised to the structure we '
        'were handed rather than the course being re-cut')
    assert plan.author == 'template'


def test_overlay_keeps_pack_fields_and_adds_depth(base_entries):
    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT, BARE_CONCEPT})
    plan, _ = blueprint.parse(document, author='template')
    assert plan is not None

    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)
    entry = course.concepts[GRAPH_CONCEPT]
    original = base_entries[GRAPH_CONCEPT]

    for key in ('id', 'unit', 'strand', 'topic', 'tier', 'difficulty', 'prerequisites',
                'graph_id', 'course_id'):
        assert entry[key] == original[key], f'{key} must come from the pack, not the plan'
    assert entry['generated'] is True, (
        'the prose is model output and the audit requires it to say so; an overlay must '
        'not launder that into "authored"')
    assert entry['overlay'] is True
    assert entry['origin'] == synthesize.ORIGIN
    assert entry['lesson_id'] == GRAPH_CONCEPT
    kinds = [block.get('kind') for block in entry['blocks']]
    assert kinds.count('concept') >= 2
    assert 'worked_example' in kinds and 'misconception' in kinds
    items = [item for item in course.questions.values()
             if item.get('concept_id') == GRAPH_CONCEPT]
    assert len(items) >= 4
    assert all(len(item['options']) == 4 for item in items)


def test_a_framed_course_survives_the_round_trip_through_its_own_document(base_entries):
    """``parse(plan.to_dict())`` must return the same ids, including the long ones.

    This was a real defect and an expensive one: the expansion pass re-parses the framed
    plan after merging the prose in, and ``concept_id`` truncates to 48 characters. The
    AP Micro pack has 34 nodes longer than that, so the second read shortened their ids
    and the build could no longer find them in the pack - 34 of 57 lessons silently
    vanished, and the audit's complaint was "planned but no lesson was built", which
    points at the writer rather than at the id rule.
    """
    document = _written_document(list(base_entries.values()), set(base_entries))
    first, _ = blueprint.parse(document, author='template')
    assert first is not None
    again, _ = blueprint.parse(first.to_dict(), author='template')
    assert again is not None

    assert {concept.id for concept in again.concepts()} == set(base_entries), (
        'every pack id survives, including the ones over the 48-character ceiling')
    long_ids = [concept.id for concept in again.concepts() if len(concept.id) > 48]
    assert long_ids, 'the pack really does carry ids this long; the test would be vacuous'
    for concept_id in long_ids:
        assert concept_id in base_entries, f'{concept_id!r} is not a pack id'


def test_the_diagram_follows_the_concept_rather_than_the_template(base_entries):
    """Two concepts, two shapes - and the shape each one gets is the one about *it*.

    The failure this is aimed at is a figure layer that always draws a market: a learner
    on an accounting distinction would be handed a crossing of two lines and taught that
    every economics idea looks like that. It also pins the choice to the pack's own text:
    a rewrite of the summary must not move a concept to a different diagram.
    """
    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT, BARE_CONCEPT})
    plan, _ = blueprint.parse(document, author='template')
    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)

    market = course.concepts[GRAPH_CONCEPT]
    figures = [block for block in market['blocks'] if block.get('kind') == 'figure']
    assert len(figures) == 1
    assert figures[0]['svg'].startswith('<svg')
    assert figures[0]['figure_kind'] == 'elasticity'
    assert market['figure']['parameters'], 'a diagram states the parameters it was drawn with'

    accounting = course.concepts[BARE_CONCEPT]
    parts = [block for block in accounting['blocks'] if block.get('kind') == 'figure']
    assert len(parts) == 1, 'the cost split is drawn, because it is what the concept is'
    assert parts[0]['figure_kind'] == 'profit_bars'
    assert accounting['figure']['parameters']['economic_profit'] < \
        accounting['figure']['parameters']['accounting_profit'], (
        'the decomposition the figure shows is the point of the concept')

    assert market['figure']['kind'] != accounting['figure']['kind'], (
        'one shape for every concept is the failure mode, not the goal')


def test_publishing_an_overlay_deepens_the_shipped_course(tmp_path, monkeypatch,
                                                          base_entries):
    monkeypatch.setenv('HARNESS_DATA_DIR', str(tmp_path))
    from app.config import Settings
    settings = Settings.from_env()

    before = curriculum.authored_share(COURSE_ID)
    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT})
    plan, _ = blueprint.parse(document, author='template')
    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)
    report = audit_module.audit(course, overlay=True)
    assert report.ok, [finding.message for finding in report.errors]

    registry.store_overlay(settings, course, report)

    after = curriculum.authored_share(COURSE_ID)
    assert after['authored_concepts'] == before['authored_concepts'], (
        'a model-written lesson is not hand-written; the authored count must not move')
    assert after['written_concepts'] == before['written_concepts'] + 1
    assert after['model_drafted_concepts'] == before['model_drafted_concepts'] + 1, (
        'the new lesson is model-drafted and unreviewed; it must be counted as that, '
        'not folded into the reviewed total')
    assert after['reviewed_concepts'] == before['reviewed_concepts'], (
        'nothing was reviewed by a person, so the reviewed count cannot move')
    assert after['overlay_concepts'] == 1
    assert curriculum.CONCEPTS[GRAPH_CONCEPT]['lesson_id'] == GRAPH_CONCEPT
    assert courses.graph_for(COURSE_ID).nodes[GRAPH_CONCEPT].has_lesson is True
    assert courses.course(COURSE_ID).authored is False, (
        'the course is deepened, not authored; the picker says who wrote the lessons')
    assert COURSE_ID not in [record.id for record in registry.load_all(settings)
                             if record.kind == 'course'], (
        'an overlay is not a second course')


def test_withdrawing_an_overlay_restores_the_shipped_course(tmp_path, monkeypatch,
                                                           base_entries):
    monkeypatch.setenv('HARNESS_DATA_DIR', str(tmp_path))
    from app.config import Settings
    settings = Settings.from_env()

    original_entry = dict(curriculum.CONCEPTS[GRAPH_CONCEPT])
    original_items = {qid: dict(item) for qid, item in curriculum.QUESTIONS.items()
                      if item.get('concept_id') == GRAPH_CONCEPT}

    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT})
    plan, _ = blueprint.parse(document, author='template')
    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)
    registry.store_overlay(settings, course)

    registry.unregister(COURSE_ID)

    restored = curriculum.CONCEPTS[GRAPH_CONCEPT]
    assert restored.get('generated') is True
    assert restored['blocks'] == original_entry['blocks']
    restored_items = {qid: item for qid, item in curriculum.QUESTIONS.items()
                      if item.get('concept_id') == GRAPH_CONCEPT}
    assert set(restored_items) == set(original_items), (
        'the generated items displaced by the overlay come back')
    assert courses.graph_for(COURSE_ID).nodes[GRAPH_CONCEPT].has_lesson is False
    assert courses.course(COURSE_ID).authored is False


def test_an_overlay_restores_the_structural_items_it_displaces(base_entries):
    """Deepening may not be a trade against coverage.

    Publishing an overlay drops the old items for the concepts it rewrote, because those
    items ask about a summary the new lesson no longer contains. If the overlay then
    contributed only its own two items, a concept that arrived with four would ship with
    two - an overlay that makes a course worse while claiming to deepen it.
    """
    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT, BARE_CONCEPT})
    plan, _ = blueprint.parse(document, author='template')
    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)

    before = [qid for qid, item in curriculum.QUESTIONS.items()
              if item.get('concept_id') == GRAPH_CONCEPT]
    after = [qid for qid, item in course.questions.items()
             if item.get('concept_id') == GRAPH_CONCEPT]
    assert set(before) <= set(after), (
        'every structural item the concept already had is minted again at the same id')
    for qid in before:
        assert course.questions[qid]['answer_text'] == curriculum.QUESTIONS[qid]['answer_text'], (
            'the regenerated item answers the same question the pack did; regenerating is '
            'deterministic, not a rewrite')


def test_a_lesson_written_alone_gets_no_under_optioned_items(base_entries):
    """A generated item with three distractors is refused, and the refusal is reported.

    Distractors are other concepts' prose. Write one concept on its own and there is none
    to draw on, so the two items that need them cannot be built at four options. Three
    options would mean guessing scores 33% instead of 25% and the per-distractor diagnoses
    would be incomplete - an item that is quietly easier than its neighbours. So it is not
    minted, and the note says why rather than leaving the lesson looking complete.
    """
    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT})
    plan, _ = blueprint.parse(document, author='template')
    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)

    items = [item for item in course.questions.values()
             if item.get('concept_id') == GRAPH_CONCEPT]
    assert items, 'the structural four are always buildable'
    assert all(len(item['options']) == 4 for item in items)
    assert not [item for item in items
                if item['category'] in ('misconception_repair', 'application_transfer')], (
        'neither deeper item is minted with only two or three options')
    assert any('distractors' in note for note in course.notes), (
        'the withheld items are reported, not silently dropped')


def test_a_concept_the_course_does_not_own_is_reported_not_invented(base_entries):
    """A plan may name a concept the pack never declared. It is skipped and said so.

    Inventing the node would create a concept no prerequisite edge reaches - visible in
    the map as an island, and ungradeable by diagnosis, which walks the graph.
    """
    document = _written_document(list(base_entries.values()), {GRAPH_CONCEPT})
    household = next(unit for unit in document['units']
                     if any(concept['id'] == GRAPH_CONCEPT for concept in unit['concepts']))
    target = next(concept for concept in household['concepts']
                  if concept['id'] == GRAPH_CONCEPT)
    target['id'] = 'ap_microeconomics_a_node_the_pack_never_declared'
    plan, _ = blueprint.parse(document, author='template')
    assert plan is not None

    course = synthesize.build_overlay(plan, course=courses.course(COURSE_ID),
                                      graph=courses.graph_for(COURSE_ID), base=base_entries)

    assert course.concepts == {}, 'a concept the base does not own is never invented'
    assert any('not owned by' in note for note in course.notes)
